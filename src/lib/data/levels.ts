/** 获取已发布的关卡 */
export function getPublishedLevels(): Level[] {
  return levels.filter((l) => l.status === "published");
}

/** 按 slug 获取关卡 */
export function getLevelBySlug(slug: string): Level | undefined {
  return levels.find((l) => l.slug === slug);
}

/** 按 ID 获取关卡 */
export function getLevelById(id: string): Level | undefined {
  return levels.find((l) => l.id === id);
}

/** 按 Level ID 获取关卡 */
export function getLevelByLevelId(levelId: string): Level | undefined {
  return levels.find((l) => l.levelId === levelId);
}

/** 按 Demon 难度筛选 */
export function getLevelsByDemonDifficulty(
  diff: "easy" | "medium" | "hard" | "insane" | "extreme"
): Level[] {
  return getPublishedLevels().filter((l) => l.demonDifficulty === diff);
}

/** 获取 First Demon 候选 */
export function getFirstDemonCandidates(): Level[] {
  return getPublishedLevels().filter((l) =>
    l.skillTags.includes("first-demon")
  );
}

/** 获取移动端友好关卡 */
export function getMobileFriendlyLevels(): Level[] {
  return getPublishedLevels().filter((l) =>
    l.skillTags.includes("mobile-friendly")
  );
}
